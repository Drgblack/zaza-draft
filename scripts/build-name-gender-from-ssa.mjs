import fs from "node:fs"
import path from "node:path"
import readline from "node:readline"

const SOURCE_DIR = process.env.SSA_DIR || "C:\\Users\\User\\Downloads\\names"
const OUT_FILE = path.join(process.cwd(), "src", "generated", "name-gender.ts")

// Conservative thresholds (tweak later if needed)
const MIN_TOTAL = 200
const MIN_RATIO = 0.95

function normaliseName(raw) {
  return String(raw || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-zà-ž'\-]/gi, "") // keep letters + common name punctuation
}

async function* walkFiles(dir) {
  const entries = await fs.promises.readdir(dir, { withFileTypes: true })
  for (const ent of entries) {
    const full = path.join(dir, ent.name)
    if (ent.isDirectory()) yield* walkFiles(full)
    else yield full
  }
}

async function readYobFiles(sourceDir) {
  const totals = new Map() // name -> { m: number, f: number }

  for await (const file of walkFiles(sourceDir)) {
    const base = path.basename(file)
    if (!/^yob\d{4}\.txt$/i.test(base)) continue

    const rl = readline.createInterface({
      input: fs.createReadStream(file, { encoding: "utf8" }),
      crlfDelay: Infinity,
    })

    for await (const line of rl) {
      if (!line) continue
      const parts = line.split(",")
      if (parts.length !== 3) continue

      const name = normaliseName(parts[0])
      const sex = String(parts[1]).trim().toUpperCase()
      const count = Number(parts[2])

      if (!name || !Number.isFinite(count) || count <= 0) continue
      if (sex !== "M" && sex !== "F") continue

      const cur = totals.get(name) || { m: 0, f: 0 }
      if (sex === "M") cur.m += count
      else cur.f += count
      totals.set(name, cur)
    }
  }

  return totals
}

function classify(totals) {
  const out = new Map() // name -> "m" | "f" | "u"

  for (const [name, { m, f }] of totals.entries()) {
    const total = m + f
    if (total < MIN_TOTAL) continue

    const mRatio = m / total
    const fRatio = f / total

    if (mRatio >= MIN_RATIO) out.set(name, "m")
    else if (fRatio >= MIN_RATIO) out.set(name, "f")
    else out.set(name, "u")
  }

  // Include a small set of common ambiguous names even if under threshold
  // so Auto can safely fall back to "u" rather than "unknown"
  const commonAmbiguous = ["alex", "sam", "jamie", "taylor", "casey", "jordan", "lee", "chris", "morgan", "pat"]
  for (const n of commonAmbiguous) {
    if (!out.has(n)) out.set(n, "u")
  }

  return out
}

function emitTs(map) {
  const header = `// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by scripts/build-name-gender-from-ssa.mjs
// Source: SSA yobYYYY.txt files (Name,Sex,Count)
// Thresholds: MIN_TOTAL=${MIN_TOTAL}, MIN_RATIO=${MIN_RATIO}

export type NameGender = "m" | "f" | "u"

export const NAME_GENDER: Record<string, NameGender> = {
`

  const entries = [...map.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))
  const body = entries.map(([name, g]) => `  ${JSON.stringify(name)}: ${JSON.stringify(g)},`).join("\n")

  const footer = `
}

export function inferGenderFromName(firstName: string): NameGender {
  const key = String(firstName || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-zà-ž'\\-]/gi, "")
  return NAME_GENDER[key] ?? "u"
}
`

  return header + body + footer
}

async function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`SSA_DIR not found: ${SOURCE_DIR}`)
    process.exit(1)
  }

  console.log(`Reading SSA yob files from: ${SOURCE_DIR}`)
  const totals = await readYobFiles(SOURCE_DIR)
  console.log(`Unique names read: ${totals.size}`)

  const classified = classify(totals)
  console.log(`Names written (>= thresholds): ${classified.size}`)

  const ts = emitTs(classified)
  await fs.promises.mkdir(path.dirname(OUT_FILE), { recursive: true })
  await fs.promises.writeFile(OUT_FILE, ts, "utf8")
  console.log(`Wrote: ${OUT_FILE}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
